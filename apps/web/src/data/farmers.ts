export const farmerById = (id: string) => farmers.find((f) => f.id === id)

// Derived from the contract's own farmerIds (rather than each farmer's
// contractIds) so a farmer added to a contract at runtime via a confirmed
// match request shows up immediately without mutating the farmer record.
export const farmersByContract = (contractId: string, contractList: Contract[] = contracts): Farmer[] => {
  const contract = contractList.find((c) => c.id === contractId)
  if (!contract) return []
  return contract.farmerIds.map((id) => farmers.find((f) => f.id === id)).filter((f): f is Farmer => !!f)
}